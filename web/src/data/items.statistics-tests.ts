import type { Item, SourceRef } from "../lib/assessment/types";

/**
 * Servable items for cluster 3 of the `statistics` domain — the eleven named
 * tests and resampling, 8 items each, authored from
 * `assessments/named-tests-and-resampling.md` and the wiki articles in
 * `data/wiki/`.
 *
 * The cluster is written so the tests read as one template with different
 * assumptions about what is known, rather than eleven recipes: what changes
 * between the z and t tests is the reference distribution and not the
 * arithmetic; what changes between the test and the interval for a proportion
 * is whether the null's variance is assumed; what changes between paired and
 * unpaired is a covariance term. Items are deliberately cross-referential in
 * that direction, and the misconception tags follow it — a learner who uses p̂
 * where p₀ belongs is debited on the proportions test, not on arithmetic.
 *
 * Closure notes. `wilcoxon-rank-sum-test` is downstream of `order-statistics`
 * and `hypothesis-test` but *not* of `one-sample-t-test`, so its items cannot
 * assume the t-test — the comparison against a mean-based test is therefore
 * framed in terms the learner has (sensitivity of an average to one extreme
 * value) rather than by naming the t-test as a prerequisite. `bootstrapping`
 * likewise excludes `confidence-interval` and `hypothesis-test`, so its items
 * stay on the sampling distribution it is estimating.
 *
 * `checkPrereqClosure` caught fourteen items reaching for a sibling concept
 * rather than an ancestor: `confidence-interval` from the one-sample tests,
 * `p-value` from Fisher's exact test, and `order-statistics` and
 * `sampling-methods` from bootstrapping. In `concepts.ts` each of those branches
 * off the shared upstream rather than sitting on the path to the test, so a
 * learner arriving legitimately need not have met it. All fourteen are
 * answerable from what their own stem supplies — the critical multiplier, the
 * tail probability, or the interval itself is given rather than assumed — so the
 * tags were dropped rather than the graph widened, following the precedent set
 * by the graphical-models sweep. Whether `confidence-interval` genuinely belongs
 * upstream of the named tests is a real question about the graph and deserves
 * its own decision.
 */

