import type { Item, SourceRef } from "../lib/assessment/types";

/**
 * Servable items for cluster 2 of the `statistics` domain — the eight inference
 * machinery concepts, 8 items each, authored from
 * `assessments/hypothesis-testing-machinery.md` and the wiki articles in
 * `data/wiki/`.
 *
 * This is where the domain's recurring misreadings live, so the distractors are
 * built from them rather than invented: a histogram of the data mistaken for a
 * sampling distribution, SD confused with SE, p read as P(H₀ | data), "95%
 * probability θ is in this interval", and non-significance read as proof of no
 * effect. Every one of those is a real wrong answer with a named misconception
 * and a blameConceptId, so the grader can say which idea failed.
 *
 * Two notes on prerequisite closures, both cases where `checkPrereqClosure`
 * caught an item reaching for something the learner may not have met.
 *
 * `confidence-interval` sits downstream of `standard-error` and
 * `sampling-distribution` but *not* of `hypothesis-test`, `test-statistic` or
 * `p-value` — so interval items may not lean on testing vocabulary, and the
 * CI/test duality is deliberately assessed from the `rejection-region` side,
 * where the closure permits it.
 *
 * Conversely `standard-error` is not upstream of `test-statistic`,
 * `hypothesis-test`, `p-value` or `type-i-ii-error`: in `concepts.ts` it is a
 * sibling branch off `sampling-distribution` rather than a step on the path to
 * testing. Ten items here were initially tagged with it. The quantity they
 * actually use is the spread of the sampling distribution, σ/√n, which
 * `sampling-distribution` already owns and which those concepts do have in
 * closure — so they are retagged to it rather than widening the graph, and each
 * stem supplies any standard error it needs as a given rather than assuming the
 * learner can derive one. Whether `standard-error` genuinely belongs upstream of
 * `test-statistic` is a real question about the graph, and worth its own
 * decision rather than a side effect of authoring.
 */

