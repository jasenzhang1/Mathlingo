/**
 * Servable items for cluster 4 of the `statistics` domain — the six concepts
 * added to carry the domain past a single comparison, 8 items each, authored
 * from `assessments/beyond-a-single-comparison.md` and the wiki articles in
 * `data/wiki/`.
 *
 * These concepts were added to the graph specifically because the existing
 * articles referenced them with nothing behind them, so the items lean into
 * that: the pooled-versus-unpooled standard error the one-sample proportions
 * test contrasts, the effect size four articles tell the reader to report, the
 * equivalence test named as the way to establish absence, and the prediction
 * interval the confidence-interval article distinguishes itself from.
 *
 * Closure note. Prerequisites were chosen when the concepts were added so that
 * each one's closure contains what its items need — `equivalence-testing` sits
 * below both `confidence-interval` and `hypothesis-test`, which is what lets its
 * items discuss the interval and the test together, something no pre-existing
 * statistics concept could do. One edge was corrected while authoring:
 * `effect-size` originally sat below `hypothesis-test` and `standard-error`,
 * which left `p-value` out of closure even though contrasting the two is the
 * whole point of the concept. It now sits below `p-value` directly.
 */

