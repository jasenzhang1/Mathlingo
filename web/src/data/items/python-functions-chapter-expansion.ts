import type { CognitiveLevel, Item, SourceRef } from "../../lib/assessment/types";

/**
 * Brings every lesson in the Functions chapter to 40 questions. `python-functions`
 * already had 49; the six lessons after it had 11 each (8 in
 * items/python-functions-chapter.ts, 3 code exercises in
 * items/python-code-functions.ts), so each gains 29 here — 8 recall, 5 apply,
 * 8 explain, 8 transfer — which evens out a pool that was apply-heavy and had a
 * single transfer item.
 *
 * None of these are `code` items: every answer is fixed by Python's semantics
 * and was checked by reading, not by running a sandbox. The builders below only
 * remove boilerplate; each item is an ordinary `Item`, and every distractor
 * still names the misconception it diagnoses.
 */

const AUTHORED: SourceRef = {
  id: "mathlingo-authored-python",
  tier: "generated",
  title: "Mathlingo authored item (Python sweep)",
};

type Distractor = [text: string, misconceptionId: string, why: string];
type RubricElement = [id: string, description: string, weight: number, required?: boolean];

function base(conceptId: string, slug: string, cognitive: CognitiveLevel, difficulty: number, seconds: number) {
  return {
    id: `${conceptId}--${slug}`,
    conceptId,
    cognitive,
    difficulty,
    discrimination: 1.2,
    expectedSeconds: seconds,
    prereqClosure: [conceptId],
    source: AUTHORED,
    status: "live" as const,
  };
}

function mcq(
  conceptId: string,
  slug: string,
  cognitive: CognitiveLevel,
  difficulty: number,
  seconds: number,
  stem: string,
  correct: string,
  distractors: Distractor[],
): Item {
  return {
    ...base(conceptId, slug, cognitive, difficulty, seconds),
    format: "mcq",
    channels: ["typed"],
    stem,
    choices: [
      { id: "a", text: correct, correct: true },
      ...distractors.map(([text, id, description], i) => ({
        id: String.fromCharCode(98 + i),
        text,
        correct: false,
        misconception: { id, description, blameConceptId: conceptId },
      })),
    ],
  };
}

function short(
  conceptId: string,
  slug: string,
  cognitive: CognitiveLevel,
  difficulty: number,
  seconds: number,
  stem: string,
  elements: RubricElement[],
): Item {
  return {
    ...base(conceptId, slug, cognitive, difficulty, seconds),
    format: "short-answer",
    channels: ["typed", "spoken"],
    stem,
    rubric: {
      elements: elements.map(([id, description, weight, required]) => ({ id, description, weight, ...(required ? { required } : {}) })),
    },
  };
}

function num(
  conceptId: string,
  slug: string,
  cognitive: CognitiveLevel,
  difficulty: number,
  seconds: number,
  stem: string,
  answerKey: number,
): Item {
  return {
    ...base(conceptId, slug, cognitive, difficulty, seconds),
    format: "numeric",
    channels: ["typed"],
    stem,
    answerKey,
    tolerance: 0.001,
  };
}

