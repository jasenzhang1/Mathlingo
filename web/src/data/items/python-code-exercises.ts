/**
 * `code`-format items: the learner writes actual Python, and the grader runs
 * it against `codeTests` in a sandboxed interpreter (Pyodide in the browser,
 * a real CPython subprocess in `tools/verifyTemplates.ts` at authoring time)
 * rather than judging free text or matching a multiple-choice key.
 *
 * Each item carries a `referenceSolution` — never shipped to the client —
 * that `verify:items` runs against the item's own `codeTests` to confirm they
 * are actually satisfiable before the item ever reaches `status: "live"`.
 * These sit alongside the multiple-choice/short-answer pools for their
 * concept rather than replacing them: writing code is a different skill from
 * recognizing the right answer, worth its own item type, not a substitute.
 *
 * Every concept in the `python` domain carries three of these, so an
 * assessment always has code to serve; `CODE_ITEM_QUOTA` in
 * `lib/assessment/review.ts` is what makes sure it actually gets served rather
 * than losing to a multiple-choice item on difficulty fit.
 *
 * Two authoring rules hold for everything here, both enforced by
 * `npm run verify:items`:
 *
 *  * The `referenceSolution` passes every one of the item's own `codeTests`.
 *  * No test passes against the item's own `starterCode` — a check that the
 *    unimplemented stub satisfies is credit for having written nothing, and
 *    since the rubric is "fraction of tests passed" it would inflate the
 *    grade of an empty submission. This is why the assertions about *not*
 *    mutating an input always also assert the returned value: on its own,
 *    "the input list is unchanged" is trivially true of a function with no
 *    body.
 *
 * NumPy and pandas items declare `codePackages` so Pyodide loads the package
 * before the first test runs. Their tests import what they need in `run`
 * rather than relying on the import in `starterCode`, which the learner is
 * free to delete.
 */

