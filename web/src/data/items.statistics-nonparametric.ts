import type { Item, SourceRef } from "../lib/assessment/types";

/**
 * Servable items for cluster 5 of the `statistics` domain — the five
 * distribution-free concepts added alongside the existing rank-sum test and
 * bootstrap, 8 items each, authored from
 * `assessments/distribution-free-methods.md` and the wiki articles in
 * `data/wiki/`.
 *
 * The cluster is written as a family rather than five recipes: the signed-rank
 * test sits on a ladder between the paired t and the sign test, Kruskal-Wallis
 * reduces to rank-sum at k = 2 the way a 2x2 chi-square reduces to a
 * two-proportion z, McNemar explains why the ordinary independence test is the
 * wrong tool for paired categorical data, the permutation test supplies the
 * general machinery all of them are special cases of, and KS answers the
 * binning objection the goodness-of-fit article raised against itself.
 *
 * Closure note. `kruskal-wallis-test`, `mcnemar-test` and
 * `kolmogorov-smirnov-test` sit off the branch that leads to `p-value`, so
 * items here talk about thresholds and critical values rather than tagging that
 * concept. `permutation-test` and `wilcoxon-signed-rank-test` do have it in
 * closure and use it directly.
 */

